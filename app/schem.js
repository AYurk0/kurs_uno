// ================================================= узловой анализ: K(p) = N/D
// Метод модифицированных узловых потенциалов (МНА) в комплексной форме.
// Активные проводимости: R -> 1/R ; C -> pC ; L -> 1/(pL).
function проводимость(р,p){
 if(р.тип==="R")return C(1/р.зн,0);
 if(р.тип==="C")return cM(p,C(р.зн,0));
 if(р.тип==="L")return cD(C(1,0),cM(p,C(р.зн,0)));
 return C(0,0);}

// p=0: катушка — замыкание (Z=pL -> 0), ёмкость — разрыв. Чтобы не получить
// 1/(pL)=∞, узлы, соединённые катушкой, ОБЪЕДИНЯЕМ. Для p≠0 объединений нет.
function картаУзлов(нт,p){
 var малый=(cAbs(p)<1e-18),N=нт.узлов,родитель=[],i;
 for(i=0;i<=N;i++)родитель[i]=i;
 function найти(k){while(родитель[k]!==k){родитель[k]=родитель[родитель[k]];k=родитель[k];}return k;}
 function объединить(a,b){var ra=найти(a),rb=найти(b);if(ra!==rb)родитель[rb]=ra;}
 if(малый)нт.ребра.forEach(function(р){if(р.тип==="L")объединить(р.a,р.b);});
 var отобр=[],след=0;
 for(i=0;i<=N;i++){
  var r=найти(i);
  if(i===0)отобр[0]=0;                       // земля всегда узел 0
  else{if(отобр[r]===undefined)отобр[r]=++след;отобр[i]=отобр[r];}}
 нт.ребра.forEach(function(р){р._a=отобр[р.a];р._b=отобр[р.b];});
 var ист=null;
 if(нт.источник)ист={плюс:отобр[нт.источник.плюс],минус:отобр[нт.источник.минус],зн:нт.источник.зн};
 return {след:след,ист:ист,отобр:отобр};}

function матрица(нт,p){
 var кар=картаУзлов(нт,p),n=кар.след,iz=n+1; // узлы 1..n + ток источника
 var A=[],i,j;
 for(i=0;i<iz;i++){A.push(new Array(iz));for(j=0;j<iz;j++)A[i][j]=C(0,0);}
 function Y(k,l,v){if(k===0||l===0)return;A[k-1][l-1]=cA(A[k-1][l-1],v);}
 var ноль=C(0,0);
 нт.ребра.forEach(function(р){
  var Yv=проводимость(р,p),mY=cS(ноль,Yv);
  Y(р._a,р._a,Yv);Y(р._b,р._b,Yv);Y(р._a,р._b,mY);Y(р._b,р._a,mY);});
 var b=new Array(iz);for(i=0;i<iz;i++)b[i]=C(0,0);
 var ист=кар.ист;
 if(ист){
  var jp=n,пл=ист.плюс-1,ми=ист.минус-1;
  // Неизвестные: u_k (узлы 1..n) и ток j через ветвь источника.
// Ток j входит в узел «+» со знаком + и в узел «−» со знаком −;
// последняя строка — само уравнение источника u(+) − u(−) = E.
if(пл>=0)A[пл][jp]=cA(A[пл][jp],C(1,0));
  if(ми>=0)A[ми][jp]=cA(A[ми][jp],C(-1,0));
  if(пл>=0)A[n][пл]=cA(A[n][пл],C(1,0));
  if(ми>=0)A[n][ми]=cA(A[n][ми],C(-1,0));
  b[n]=C(ист.зн||1,0);}
 return {A:A,b:b,iz:iz,след:n,ист:ист,карта:кар};}

// Решение комплексной системы методом Гаусса с частичным выбором ведущего
function решитьСистему(с){
 var A=с.A.map(function(ст){return ст.slice();});
 var b=с.b.map(function(v){return cM(v,C(1,0));});
 var iz=с.iz,i,j,k;
 for(k=0;k<iz;k++){
  var вед=k,мод=cAbs(A[k][k]);
  for(i=k+1;i<iz;i++){var v=cAbs(A[i][k]);if(v>мод){мод=v;вед=i;}}
  if(мод<1e-300)return null;
  if(вед!==k){var t=A[k];A[k]=A[вед];A[вед]=t;var tb=b[k];b[k]=b[вед];b[вед]=tb;}
  for(i=k+1;i<iz;i++){
   var f=cD(A[i][k],A[k][k]);if(cAbs(f)<1e-300)continue;
   for(j=k;j<iz;j++)A[i][j]=cS(A[i][j],cM(f,A[k][j]));
   b[i]=cS(b[i],cM(f,b[k]));}}
 var x=new Array(iz);
 for(i=iz-1;i>=0;i--){var s=b[i];
  for(j=i+1;j<iz;j++)s=cS(s,cM(A[i][j],x[j]));
  x[i]=cD(s,A[i][i]);}
 return x;}

// K(p) = ΔUвых/ΔUвх, источник 1 В.
// Для четырёхполюсника (выход2 != null) ΔUвых = U(выход) − U(выход2).
function KСхемы(нт,p){
 if(!нт||!нт.источник||нт.выход===null)return C(0,0);
 var с=матрица(нт,p),x=решитьСистему(с);
 if(!x||!с.ист)return C(0,0);
 var вых=с.карта.отобр[нт.выход];
 var uвх=(с.ист.плюс>0)?x[с.ист.плюс-1]:C(0,0);
 var uвых=(вых>0)?x[вых-1]:C(0,0);
 if(нт.выход2!==null&&нт.выход2!==undefined){
  var в2=с.карта.отобр[нт.выход2];
  uвых=cS(uвых,(в2>0)?x[в2-1]:C(0,0));}
 if(cAbs(uвх)<1e-300)return C(0,0);
 return cD(uвых,uвх);}
// Возведение комплексного числа в целую степень n >= 0.
// ВАЖНО: cE — это экспонента e^z, а не степень; для p^m нужен именно показатель.
function powКомплекс(z,n){var r=C(1,0),k;for(k=0;k<n;k++)r=cM(r,z);return r;}

// Масштаб для базиса полиномов: геометрическое среднее характерных частот
// элементов. Характерные частоты: для катушки R/L, для ёмкости 1/(R·C), где R —
// крайнее сопротивление схемы (для катушки берём наименьшее, для ёмкости —
// наибольшее, это даёт оценку сверху). Такой масштаб НЕ зависит от формы АЧХ:
// прежний вариант («−3 дБ от пика») у схем-ФВЧ, у которых |K| на высоких частотах
// не спадает, упирался в верхнюю границу сканирования 1e13 и круг интерполяции
// оказывался на 7 порядков выше полюсов (цепь 32).
function масштабПоЭлементам(нт){
 // ВАЖНО: имена переменных НЕ R/L/C — здесь C и R совпадают с именами
 // функций комплексного числа и матрицы, и затенение приводило к тихой
 // подстановке запасного масштаба (ошибка была найдена тестом).
 var Rs=[],Ls=[],Cs=[];
 нт.ребра.forEach(function(р){
  if(р.тип==="R"&&isFinite(р.зн)&&р.зн>0)Rs.push(р.зн);
  if(р.тип==="L"&&isFinite(р.зн)&&р.зн>0)Ls.push(р.зн);
  if(р.тип==="C"&&isFinite(р.зн)&&р.зн>0)Cs.push(р.зн);});
 if(!Ls.length&&!Cs.length)return масштабПоАЧХ(нт);
 var f=[];
 if(Ls.length&&Rs.length){var rmin=Math.min.apply(null,Rs);
  Ls.forEach(function(л){f.push(rmin/л.зн);});}
 if(Cs.length&&Rs.length){var rmax=Math.max.apply(null,Rs);
  Cs.forEach(function(ц){f.push(1/(rmax*ц.зн));});}
 if(!f.length)return масштабПоАЧХ(нт);
 f=f.filter(function(v){return isFinite(v)&&v>0;});
 if(!f.length)return масштабПоАЧХ(нт);
 f.sort(function(a,b){return a-b;});
 return f[Math.floor(f.length/2)];}

// Частота, на которой |K(jw)| падает до 0.7 от МАКСИМУМА (≈ −3 дБ).
// Используется как запасной масштаб и для оценки диапазона АЧХ в отчёте.
// Отсчёт идём от максимума |K(jw)|, а НЕ от K(0): у схем-ФВЧ (последовательная
// ёмкость) K(0)=0, и отсчёт от K(0) давал w0=1e-3 — на 6 порядков ниже полюсов.
function масштабПоАЧХ(нт){
 var kmax=0,wMax=1,w;
 for(w=1e-3;w<1e13;w*=Math.pow(10,0.25)){
  var y=cAbs(KСхемы(нт,C(0,w)));
  if(isFinite(y)&&y>kmax){kmax=y;wMax=w;}}
 if(!(kmax>0))return 0;
 var порог=0.7*kmax,hi=0,lo=wMax;
 for(w=wMax;w<1e13;w*=Math.pow(10,0.25)){
  var y2=cAbs(KСхемы(нт,C(0,w)));
  if(isFinite(y2)&&y2<порог){hi=w;break;}
  lo=w;}
 if(!(hi>0))return lo||1;
 for(var i=0;i<60;i++){
  var mid=Math.sqrt(lo*hi);
  var y3=cAbs(KСхемы(нт,C(0,mid)));
  if(isFinite(y3)&&y3>=порог)lo=mid;else hi=mid;}
 return hi;}

// Отбрасываем ТОЛЬКО истинно нулевые старшие коэффициенты. Порог относительный:
// реальные коэффициенты старших степеней бывают ~1e-12 при ведущем 1e6.
function убратьХвост(P){
 var mx=0,i;for(i=0;i<P.length;i++)mx=Math.max(mx,Math.abs(P[i]));
 if(!(mx>0))return P;
 while(P.length>1&&Math.abs(P[P.length-1])<=1e-13*mx)P.pop();
 return P;}

// Определитель комплексной матрицы методом Гаусса (перестановка строк меняет знак)
function detКомплекс(A){
 var n=A.length,i,j,k,det=C(1,0);
 var M=A.map(function(ст){return ст.slice();});
 for(k=0;k<n;k++){
  var вед=k,мод=cAbs(M[k][k]);
  for(i=k+1;i<n;i++){var v=cAbs(M[i][k]);if(v>мод){мод=v;вед=i;}}
  if(мод<1e-300)return C(0,0);
  if(вед!==k){var t=M[k];M[k]=M[вед];M[вед]=t;det=cS(C(0,0),det);}
  det=cM(det,M[k][k]);
  for(i=k+1;i<n;i++){
   var f=cD(M[i][k],M[k][k]);if(cAbs(f)<1e-300)continue;
   for(j=k;j<n;j++)M[i][j]=cS(M[i][j],cM(f,M[k][j]));}}
 return det;}

// Интерполяция Лагранжа по комплексным точкам: коэффициенты полинома
// (по ВОЗРАСТАНИЮ степени), который проходит через все (x_i, y_i).
// Требуется ровно n+1 точек для полинома степени <= n.
function интерпЛагранж(xs,ys){
 var n=xs.length;
 if(n===0)return null;
 if(n===1)return [ys[0].re,ys[0].im];
 var рез=new Array(n),i,k;
 for(i=0;i<n;i++)рез[i]=C(0,0);
 for(i=0;i<n;i++){
  // фундаментальный полином L_i(p) = Π_{j≠i} (p − x_j) / (x_i − x_j)
  var базис=[C(1,0)],знам=C(1,0);
  for(k=0;k<n;k++){
   if(k===i)continue;
   // умножаем базис на (p − x_k)
   var нов=new Array(базис.length+1);
   for(var t=0;t<базис.length+1;t++)нов[t]=C(0,0);
   for(t=0;t<базис.length;t++){
    нов[t+1]=cA(нов[t+1],базис[t]);            // · p
    нов[t]=cS(нов[t],cM(базис[t],xs[k]));      // − x_k
   }
   базис=нов;
   знам=cM(знам,cS(xs[i],xs[k]));               // · (x_i − x_k)
  }
  if(cAbs(знам)<1e-300)return null;
  // прибавляем y_i · L_i
  var t2;
  for(t2=0;t2<базис.length&&t2<n;t2++)
   рез[t2]=cA(рез[t2],cM(базис[t2],cD(ys[i],знам)));}
 var out=new Array(n);
 for(i=0;i<n;i++)out[i]=рез[i].re;   // контроль: значения должны быть вещественными
 return out;}

// Полиномы N(p)/D(p) по правилу Крамера + интерполяция Лагранжа.
// D(p) = det M(p), N(p) = det M_k(p), где у M_k k-я строка заменена на b.
// Катушка даёт проводимость 1/(pL), поэтому det M — РАЦИОНАЛЬНАЯ функция с
// полюсами в p=0; умножаем на p^m, получая полиномы степени ровно m.
function полиномыСхемы(нт){
 if(!нт||!нт.источник||нт.выход===null||нт.ребра.length<2)return null;
 var m=0;нт.ребра.forEach(function(р){if(р.тип!=="R")m++;});
 if(m<1)m=1;
 // Масштаб круга интерполяции. Берётся «−3 дБ от пика |K(jw)|».
 // ВАЖНО: отсчёт идёт ОТ ПИКА, а не от K(0). У схем-ФВЧ (последовательная
 // ёмкость: 11, 21, 22, 32, 41, 51, 61) K(0)=0, и отсчёт от K(0) давал
 // w0 = 1e-3 — на шесть порядков ниже полюсов, из-за чего коэффициенты
 // полиномов теряли точность полностью.
 var w0=масштабПоЭлементам(нт);
 var R=(w0>0)?w0/2:0.01;
 var вых=нт.выход,j,Точки=[];
 for(j=0;j<=m;j++){
  var ang=Math.PI*j/m;
  Точки.push(cM(C(Math.cos(ang),Math.sin(ang)),C(R,0)));}
 var fD=[],fN=[];
 for(j=0;j<=m;j++){
  var с=матрица(нт,Точки[j]);
  if(!с||!с.ист)return null;
  var pm=powКомплекс(Точки[j],m);
  var detM=detКомплекс(с.A);
  var d=cM(detM,pm);
  if(cAbs(d)<1e-300)return null;      // точка попала на полюс
  fD.push(d);
  // N = det M_k — правило Крамера: у матрицы k-я строка заменяется на правую
  // часть b. Для обычной схемы выход один, берётся одна замена; для
  // четырёхполюсника выходных узлов два и ΔUвых = u_a − u_b, то есть
  // det M_a − det M_b (каждый определитель от своей матрицы).
  function крамер(узел){
   if(узел===null||узел===undefined||узел<=0)return C(0,0);
   var Mk=с.A.map(function(ст){return ст.slice();});
   Mk[узел-1]=с.b.slice();
   return cM(detКомплекс(Mk),pm);}
  fN.push(нт.выход2!=null?cS(крамер(вых),крамер(нт.выход2)):крамер(вых));}
 var D=интерпЛагранж(Точки,fD),N=интерпЛагранж(Точки,fN);
 if(!D||!N)return null;
 // Нормируем на СТАРШИЙ коэффициент D (общий множитель не меняет N/D).
 var dmax=0,i;
 for(i=0;i<D.length;i++)dmax=Math.max(dmax,Math.abs(D[i]));
 if(!isFinite(dmax)||dmax<1e-300)return null;
 var norm=1/dmax;
 N=убратьХвост(N.map(function(v){return v*norm;}));
 D=убратьХвост(D.map(function(v){return v*norm;}));
 return {N:N,D:D};}
