// Выводы элемента в мировых координатах вдоль оси после поворота.
function выводы(эл){
 if(эл.т==="GND"||эл.т==="выход"||эл.т==="выход2")return [{x:эл.x,y:эл.y}];
 var u=Math.PI*(эл.пов||0)/180,c=Math.cos(u),s=Math.sin(u);
 return [{x:эл.x-ДЛИНА*c,y:эл.y-ДЛИНА*s},{x:эл.x+ДЛИНА*c,y:эл.y+ДЛИНА*s}];}

function всеТочки(){
 var t=[];
 СХЕМА.элементы.forEach(function(эл){
  if(эл.т==="провод")эл.точки.forEach(function(p){t.push({x:p.x,y:p.y});});
  else выводы(эл).forEach(function(p){t.push(p);});});
 return t;}

// Провода, «сцепленные» с элементом (вывод элемента попал на точку провода).
function сцепленныеПровода(эл){
 var res=[],мои=выводы(эл);
 СХЕМА.элементы.forEach(function(пр){
  if(пр.т!=="провод")return;
  пр.точки.forEach(function(t,i){
   for(var k=0;k<мои.length;k++)
    if(Math.abs(t.x-мои[k].x)<0.01&&Math.abs(t.y-мои[k].y)<0.01){res.push({провод:пр,i:i});break;}});});
 return res;}

// Узел — координата, к которой подходят точки ДВУХ И БОЛЕЕ разных объектов.
function узлыСхемы(){
 var карта={};
 function отметить(p,поз){
  var k=p.x+"|"+p.y;
  if(!карта[k])карта[k]={x:p.x,y:p.y,сколько:0};
  карта[k].сколько++;карта[k][поз]=1;}
 СХЕМА.элементы.forEach(function(эл){
  if(эл.т==="провод")эл.точки.forEach(function(p){отметить(p,эл.поз);});
  else выводы(эл).forEach(function(p){отметить(p,эл.поз);});});
 var рез=[];
 for(var k in карта){
  var c=карта[k],сколько=0;
  for(var pz in c)if(pz!=="x"&&pz!=="y"&&pz!=="сколько")сколько++;
  if(сколько>=2)рез.push({x:c.x,y:c.y});}
 return рез;}

// Притянуть координату к ближайшему узлу схемы (иначе — к сетке)
function магнит(x,y,кроме){
 var луч=null,бд=РАДИУС_МГНИТА;
 всеТочки().forEach(function(p){
  if(кроме&&Math.abs(p.x-кроме.x)<0.01&&Math.abs(p.y-кроме.y)<0.01)return;
  var d=Math.hypot(p.x-x,p.y-y);if(d<бд){бд=d;луч=p;}});
 if(луч)return {x:Math.round(луч.x),y:Math.round(луч.y)};
 return {x:Math.round(x/СЕТКА)*СЕТКА,y:Math.round(y/СЕТКА)*СЕТКА};}

