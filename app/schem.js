// Элемент под точкой (ближайший по расстоянию до «тела»)
function элементВТочке(p){
 var луч=null,бд=1e9;
 СХЕМА.элементы.forEach(function(эл){
  var d;
  if(эл.т==="GND"||эл.т==="выход"||эл.т==="выход2")d=Math.hypot(эл.x-p.x,эл.y-p.y)-8;
  else if(эл.т==="провод"){
   d=1e9;эл.точки.forEach(function(t){d=Math.min(d,Math.hypot(t.x-p.x,t.y-p.y));});}
  else{
   var u=Math.PI*(эл.пов||0)/180,dx=p.x-эл.x,dy=p.y-эл.y;
   var пр=dx*Math.cos(u)+dy*Math.sin(u),пер=-dx*Math.sin(u)+dy*Math.cos(u);
   d=(Math.abs(пр)>ДЛИНА)?Math.abs(пр)-ДЛИНА+40:(Math.abs(пер)>12?Math.abs(пер)-12+8:0);}
  if(d<бд){бд=d;луч=эл;}});
 return (бд<20)?луч:null;}

function вМир(событие,svg){
 var r=svg.getBoundingClientRect();
 return {x:(событие.clientX-r.left)/r.width*ХОЛСТ.W,y:(событие.clientY-r.top)/r.height*ХОЛСТ.H};}

